fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    // By default the library's install name is the path of the build: a program linked with it
    // would look for it there.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
        println!("cargo:rustc-cdylib-link-arg=-Wl,-install_name,@rpath/libmocoal.dylib");
    }
}
